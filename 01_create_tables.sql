-- 01: Create the retail analytics schema
-- Target: PostgreSQL 14+ (tested on 16). Run inside the retail_analytics database.
-- Safe to re-run: everything is dropped and rebuilt.

SET client_min_messages = WARNING;       -- hide "drop cascades" notices on re-runs
DROP SCHEMA IF EXISTS retail CASCADE;   -- removes tables, views and indexes in one step
CREATE SCHEMA retail;
RESET client_min_messages;

CREATE TABLE retail.customers (
    customer_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name       VARCHAR(60)  NOT NULL,
    last_name        VARCHAR(60)  NOT NULL,
    email            VARCHAR(150) NOT NULL UNIQUE
        CHECK (email = LOWER(email) AND email LIKE '%_@_%._%'),
    city             VARCHAR(80)  NOT NULL,
    signup_date      DATE         NOT NULL,
    customer_segment VARCHAR(20)  NOT NULL
        CHECK (customer_segment IN ('Budget', 'Regular', 'Premium'))
);

CREATE TABLE retail.categories (
    category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE retail.products (
    product_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  INTEGER       NOT NULL REFERENCES retail.categories(category_id),
    product_name VARCHAR(120)  NOT NULL UNIQUE,
    unit_cost    NUMERIC(12,2) NOT NULL CHECK (unit_cost >= 0),
    list_price   NUMERIC(12,2) NOT NULL CHECK (list_price >= 0),
    active       BOOLEAN       NOT NULL DEFAULT TRUE,
    CHECK (list_price >= unit_cost)
);

CREATE TABLE retail.orders (
    order_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  INTEGER     NOT NULL REFERENCES retail.customers(customer_id),
    order_date   DATE        NOT NULL,
    order_status VARCHAR(20) NOT NULL
        CHECK (order_status IN ('Completed', 'Processing', 'Cancelled'))
);

CREATE TABLE retail.order_items (
    order_item_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        INTEGER       NOT NULL REFERENCES retail.orders(order_id) ON DELETE CASCADE,
    product_id      INTEGER       NOT NULL REFERENCES retail.products(product_id),
    quantity        INTEGER       NOT NULL CHECK (quantity > 0),
    unit_price      NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    -- Derived columns stored once, so every query uses the same definition of "net".
    gross_amount    NUMERIC(14,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    net_amount      NUMERIC(14,2) GENERATED ALWAYS AS (quantity * unit_price - discount_amount) STORED,
    CHECK (discount_amount <= quantity * unit_price),
    UNIQUE (order_id, product_id)
);

-- Indexes (benchmarked in queries/09_performance_tuning.sql)
-- PostgreSQL does NOT index foreign-key columns automatically, so index the ones that queries filter or join on.
-- order_items(order_id) is already covered by the UNIQUE (order_id, product_id) index.
CREATE INDEX idx_products_category    ON retail.products(category_id);
CREATE INDEX idx_order_items_product  ON retail.order_items(product_id);
-- "All orders of one customer, newest first" (customer history, repeat-purchase and LAG queries).
CREATE INDEX idx_orders_customer_date ON retail.orders(customer_id, order_date);
-- Date-range reports. The status column is included so "order_status <> 'Cancelled'" is checked inside the index.
CREATE INDEX idx_orders_date_status   ON retail.orders(order_date, order_status);

-- Confirm the tables were created.
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'retail' AND table_type = 'BASE TABLE'
ORDER BY table_name;

